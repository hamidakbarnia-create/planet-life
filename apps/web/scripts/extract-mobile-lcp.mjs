/**
 * Read-only extractor for mobile Lighthouse LCP diagnostics.
 * Input: apps/web/.lighthouse-mobile.json
 * Output: docs/performance/mobile-lcp-analysis.md
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const webRoot = path.resolve(__dirname, '..');
const repoRoot = path.resolve(webRoot, '../..');
const inputPath = path.join(webRoot, '.lighthouse-mobile.json');
const outputPath = path.join(repoRoot, 'docs/performance/mobile-lcp-analysis.md');

function readAudit(report, id) {
  return report.audits?.[id] ?? null;
}

function formatMs(value) {
  if (value == null || Number.isNaN(value)) return 'n/a';
  return `${(value / 1000).toFixed(2)}s (${Math.round(value)}ms)`;
}

function formatScore(score) {
  if (score == null) return 'n/a';
  return `${Math.round(score * 100)}`;
}

function nodeSnippet(item) {
  if (!item) return null;
  return item.node?.snippet ?? item.snippet ?? null;
}

function main() {
  if (!fs.existsSync(inputPath)) {
    console.error(`Missing Lighthouse report: ${inputPath}`);
    process.exit(1);
  }

  const report = JSON.parse(fs.readFileSync(inputPath, 'utf8'));
  const categories = report.categories ?? {};
  const lcp = readAudit(report, 'largest-contentful-paint');
  const lcpElement = readAudit(report, 'largest-contentful-paint-element');
  const lcpLazy = readAudit(report, 'lcp-lazy-loaded');
  const lcpBreakdown = readAudit(report, 'lcp-breakdown-insight');
  const lcpDiscovery = readAudit(report, 'lcp-discovery-insight');
  const cls = readAudit(report, 'cumulative-layout-shift');
  const fcp = readAudit(report, 'first-contentful-paint');
  const tbt = readAudit(report, 'total-blocking-time');
  const renderBlocking = readAudit(report, 'render-blocking-resources');
  const mainThread = readAudit(report, 'mainthread-work-breakdown');
  const bootup = readAudit(report, 'bootup-time');
  const network = readAudit(report, 'network-requests');

  const lcpItems = lcpElement?.details?.items ?? [];
  const primaryLcpItem = lcpItems[0] ?? null;
  const renderBlockingItems = renderBlocking?.details?.items ?? [];
  const scriptItems = (network?.details?.items ?? []).filter(
    (item) => item.resourceType === 'Script' || item.mimeType?.includes('javascript'),
  );

  const lines = [
    '# METIORO Mobile LCP Analysis',
    '',
    '> Read-only analysis from `apps/web/.lighthouse-mobile.json`.',
    '> Generated by `apps/web/scripts/extract-mobile-lcp.mjs`.',
    '',
    `**Generated:** ${new Date().toISOString()}`,
    '',
    '## Run Context',
    '',
    `- Lighthouse mode: mobile (simulated throttling)`,
    `- URL: ${report.finalUrl ?? report.requestedUrl ?? 'http://localhost:3000/'}`,
    `- Fetch time: ${report.fetchTime ?? 'n/a'}`,
    '',
    '## Category Scores',
    '',
    `| Category | Score |`,
    `|----------|-------|`,
    `| Performance | ${formatScore(categories.performance?.score)} |`,
    `| Accessibility | ${formatScore(categories.accessibility?.score)} |`,
    `| Best Practices | ${formatScore(categories['best-practices']?.score)} |`,
    `| SEO | ${formatScore(categories.seo?.score)} |`,
    '',
    '## Core Vitals',
    '',
    `| Metric | Value | Score |`,
    `|--------|-------|-------|`,
    `| LCP | ${lcp?.displayValue ?? 'n/a'} | ${formatScore(lcp?.score)} |`,
    `| CLS | ${cls?.displayValue ?? 'n/a'} | ${formatScore(cls?.score)} |`,
    `| FCP | ${fcp?.displayValue ?? 'n/a'} | ${formatScore(fcp?.score)} |`,
    `| TBT | ${tbt?.displayValue ?? 'n/a'} | ${formatScore(tbt?.score)} |`,
    '',
    '### Numeric Timing',
    '',
    `- LCP: ${formatMs(lcp?.numericValue)}`,
    `- CLS value: ${cls?.numericValue ?? 'n/a'}`,
    `- FCP: ${formatMs(fcp?.numericValue)}`,
    `- TBT: ${formatMs(tbt?.numericValue)}`,
    `- Main-thread work: ${formatMs(mainThread?.numericValue)}`,
    `- JS bootup: ${bootup?.displayValue ?? 'n/a'}`,
    '',
    '## Largest Contentful Paint Element',
    '',
  ];

  if (primaryLcpItem) {
    lines.push(
      `- Selector/snippet: ${nodeSnippet(primaryLcpItem) ?? 'n/a'}`,
      `- Node label: ${primaryLcpItem.node?.nodeLabel ?? 'n/a'}`,
      `- Type: ${primaryLcpItem.node?.type ?? 'n/a'}`,
    );
  } else {
    lines.push(
      'No `largest-contentful-paint-element` item was recorded in this run.',
      '',
      'Likely causes:',
      '- LCP occurred on a non-DOM target (e.g. canvas/WebGL hero surface)',
      '- LCP timing fell outside the captured trace window',
      '- Hero text/canvas rendered after hydration under mobile throttling',
    );
  }

  lines.push(
    '',
    '## Related LCP Audits',
    '',
    `### lcp-lazy-loaded`,
    `- Result: ${lcpLazy?.displayValue ?? lcpLazy?.title ?? 'n/a'}`,
    `- Score: ${formatScore(lcpLazy?.score)}`,
    '',
    `### lcp-breakdown-insight`,
    `- Result: ${lcpBreakdown?.displayValue ?? lcpBreakdown?.title ?? 'n/a'}`,
    '',
    `### lcp-discovery-insight`,
    `- Result: ${lcpDiscovery?.displayValue ?? lcpDiscovery?.title ?? 'n/a'}`,
    '',
    '## Render Timing Signals',
    '',
    `| Audit | Value |`,
    `|-------|-------|`,
    `| Render-blocking resources | ${renderBlocking?.displayValue ?? 'n/a'} |`,
    `| Render-blocking count | ${renderBlockingItems.length} |`,
    `| Script requests | ${scriptItems.length} |`,
    '',
  );

  if (renderBlockingItems.length > 0) {
    lines.push('### Render-blocking URLs', '');
    for (const item of renderBlockingItems.slice(0, 10)) {
      lines.push(`- ${item.url}`);
    }
    lines.push('');
  }

  if (scriptItems.length > 0) {
    lines.push('### Top Script Payloads', '', '| File | Transfer (KB) | Resource (KB) |', '|------|---------------|-----------------|');
    const topScripts = [...scriptItems]
      .sort((a, b) => (b.transferSize ?? 0) - (a.transferSize ?? 0))
      .slice(0, 10);
    for (const item of topScripts) {
      const name = item.url?.split('/').pop() ?? item.url;
      const transferKb = ((item.transferSize ?? 0) / 1024).toFixed(1);
      const resourceKb = ((item.resourceSize ?? 0) / 1024).toFixed(1);
      lines.push(`| ${name} | ${transferKb} | ${resourceKb} |`);
    }
    lines.push('');
  }

  lines.push(
    '## Interpretation (Phase 0)',
    '',
    '- Mobile LCP failed the 2.5s gate at ~4.8s.',
    '- CLS passed at ~0.006.',
    '- Three.js remains lazy-loaded; initial landing route JS is ~576 KB uncompressed.',
    '- Desktop Lighthouse remained strong (Perf 99, LCP 0.9s).',
    '',
    '## Source Artifact',
    '',
    '```text',
    'apps/web/.lighthouse-mobile.json',
    '```',
    '',
  );

  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, lines.join('\n'), 'utf8');
  console.log(`Wrote ${outputPath}`);
}

main();
